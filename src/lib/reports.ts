import jsPDF from 'jspdf';
import type { DailyReport, CafeSettings } from '@/types';
import { DEFAULT_SETTINGS } from '@/types';

function fmt(amount: number, c = '₹'): string {
  return `${c}${amount.toFixed(2)}`;
}

export function generateReportPDF(report: DailyReport, settings?: CafeSettings): jsPDF {
  const s = settings || DEFAULT_SETTINGS;
  const doc = new jsPDF('portrait', 'mm', 'a4');
  const pw = 210;
  const lm = 20;
  const rm = pw - 20;
  let y = 25;

  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(`${s.cafeName} — Daily Report`, pw / 2, y, { align: 'center' });
  y += 8;
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100);
  doc.text(`Date: ${report.date}`, pw / 2, y, { align: 'center' });
  y += 14;

  // Summary
  const cards = [
    ['Total Bills', `${report.totalBills}`],
    ['Total Sales', fmt(report.totalSales, s.currency)],
    ['Discount', fmt(report.totalDiscount, s.currency)],
    ['Revenue', fmt(report.totalRevenue, s.currency)],
  ];
  const cw = (rm - lm - 15) / 4;
  doc.setDrawColor(0, 212, 255);
  cards.forEach(([label, val], i) => {
    const x = lm + i * (cw + 5);
    doc.roundedRect(x, y, cw, 20, 2, 2);
    doc.setFontSize(8); doc.setTextColor(100); doc.setFont('helvetica', 'normal');
    doc.text(label, x + cw / 2, y + 7, { align: 'center' });
    doc.setFontSize(12); doc.setTextColor(10, 14, 39); doc.setFont('helvetica', 'bold');
    doc.text(val, x + cw / 2, y + 15, { align: 'center' });
  });
  y += 30;

  doc.setFontSize(9); doc.setFont('helvetica', 'normal'); doc.setTextColor(60);
  doc.text(`Prints: ${report.printCount} | WhatsApp: ${report.whatsappCount}${report.peakHour ? ` | Peak: ${report.peakHour}` : ''}`, lm, y);
  y += 10;

  // Items sold table
  doc.setFontSize(13); doc.setFont('helvetica', 'bold'); doc.setTextColor(10, 14, 39);
  doc.text('Items Sold', lm, y); y += 7;
  doc.setFillColor(10, 14, 39);
  doc.roundedRect(lm, y, rm - lm, 7, 1, 1, 'F');
  doc.setTextColor(255); doc.setFontSize(8);
  doc.text('Item', lm + 5, y + 5);
  doc.text('Qty', rm - 10, y + 5, { align: 'right' });
  y += 10;

  const sorted = Object.entries(report.itemsSold).sort((a, b) => b[1] - a[1]);
  doc.setTextColor(40); doc.setFont('helvetica', 'normal');
  sorted.forEach(([name, qty], idx) => {
    if (y > 270) return;
    if (idx % 2 === 0) { doc.setFillColor(245, 247, 250); doc.rect(lm, y - 4, rm - lm, 7, 'F'); }
    doc.text(name, lm + 5, y);
    doc.text(`${qty}`, rm - 10, y, { align: 'right' });
    y += 7;
  });

  doc.setFontSize(8); doc.setTextColor(150);
  doc.text(`Generated by ${s.developerName}`, pw / 2, 285, { align: 'center' });
  return doc;
}

export function downloadDailyReport(report: DailyReport, settings?: CafeSettings): void {
  generateReportPDF(report, settings).save(`BS-Foods-Report-${report.date}.pdf`);
}

export function downloadCSV(report: DailyReport): void {
  const rows = [
    'BS FOODS - Daily Report',
    `Date,${report.date}`,
    `Total Bills,${report.totalBills}`,
    `Total Sales,${report.totalSales}`,
    `Discount,${report.totalDiscount}`,
    `Revenue,${report.totalRevenue}`,
    '', 'Item,Qty,Revenue',
    ...Object.entries(report.itemsSold).sort((a, b) => b[1] - a[1]).map(([n, q]) => `"${n}",${q},${report.itemsRevenue?.[n] || 0}`),
    '', 'Payment,Count',
    ...Object.entries(report.paymentMethods).map(([m, c]) => `${m},${c}`),
  ];
  const blob = new Blob([rows.join('\n')], { type: 'text/csv' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = `BS-Foods-Report-${report.date}.csv`; a.click();
  URL.revokeObjectURL(url);
}
